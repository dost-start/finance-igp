#!/usr/bin/env python3
"""Builds src/lib/school-acronyms.generated.ts from scripts/ph-schools.json (a scrape of the Wikipedia list of
Philippine colleges and universities). For every school it derives the usual initials, with and without the
small words (of, the, de, ng...), and maps each acronym to the schools it could stand for.
Run: python3 scripts/gen-school-acronyms.py"""
import json, re, unicodedata

STOP = {"of", "the", "and", "for", "in", "at", "ng", "sa", "de", "del", "la", "las", "los", "y", "&", "a", "an"}
names = json.load(open("scripts/ph-schools.json"))

def base(n):
    n = re.sub(r"\(.*?\)", "", n).strip()
    n = re.split(r"\s+[-–]\s+|(?<=[a-z])[-–](?=[A-Z])", n)[0].strip()
    return n

bases = sorted({base(n) for n in names if len(base(n)) > 5})

def initials(words):
    s = "".join(w[0] for w in words if w)
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z]", "", s)

out = {}
for n in bases:
    words = re.findall(r"[^\s,/]+", n.replace("&", " "))
    words = [w.strip(".'’") for w in words if w.strip(".'’")]
    if len(words) < 2:
        continue
    variants = {initials(words), initials([w for w in words if w.lower() not in STOP])}
    for a in variants:
        if 3 <= len(a) <= 8:
            out.setdefault(a, set()).add(n)

def rank(n):
    t = n.lower()
    kind = 0 if "university" in t else 1 if "institute" in t else 2
    return (kind, len(n), n)

final = {a: sorted(v, key=rank)[:4] for a, v in sorted(out.items())}
body = json.dumps(final, ensure_ascii=False, separators=(",", ":"))
open("src/lib/school-acronyms.generated.ts", "w").write(
    "// GENERATED by scripts/gen-school-acronyms.py from scripts/ph-schools.json. Do not edit by hand.\n"
    "// Maps a lowercase acronym to the schools it could stand for, best guess first.\n"
    f"export const SCHOOL_ACRONYMS: Record<string, string[]> = {body};\n"
)
print(len(bases), "schools,", len(final), "acronyms")
